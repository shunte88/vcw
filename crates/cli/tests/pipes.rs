//! A reader that stops reading is not an error.
//!
//! `vcw eq list | head -3` used to print its three lines and then
//! `thread 'vcw' panicked at library/std/src/io/stdio.rs: failed printing to
//! stdout: Broken pipe (os error 32)`, because `println!` has nowhere to return
//! an error to and so panics. Every verb in this CLI prints, so every verb had
//! it, and quitting `less` is the same event.
//!
//! The fix reads the panic payload, which is the only thing a panic carries.
//! That makes it a string match on two `std` messages, so this test is what
//! stops the match going stale: it closes a real pipe on a real `vcw` and fails
//! if anything escapes. The catalog it prints is deliberately larger than any
//! platform's pipe buffer, so the child is certainly still writing when the
//! reader goes away - a short output would be swallowed whole by the buffer and
//! the test would pass without ever reproducing the thing it is about.

use std::io::Read;
use std::process::{Command, Stdio};

const VCW: &str = env!("CARGO_BIN_EXE_vcw");

/// Enough curves that `eq list` cannot fit in a pipe buffer. 64 KiB is the
/// usual Linux and macOS default and Windows is smaller; this is ~240 KB.
const CURVES: usize = 3000;

fn fat_catalog(dir: &std::path::Path) -> std::path::PathBuf {
    let mut toml = String::new();
    for i in 0..CURVES {
        toml.push_str(&format!(
            "[[curve]]\nid = \"c{i}\"\nname = \"Filler curve {i}\"\n\
             turnover_us = 318.0\ncitation = \"generated by tests/pipes.rs\"\n\n"
        ));
    }
    let path = dir.join("fat.toml");
    std::fs::write(&path, toml).expect("write the catalog");
    path
}

#[test]
fn a_closed_reader_is_not_an_error() {
    let dir = tempfile::tempdir().expect("temp dir");
    let catalog = fat_catalog(dir.path());

    let mut child = Command::new(VCW)
        .args(["eq", "list", "--curves"])
        .arg(&catalog)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn the CLI");

    // Take a little and then stop, which is what `head` does.
    let mut stdout = child.stdout.take().expect("stdout is piped");
    let mut first = [0u8; 64];
    stdout.read_exact(&mut first).expect("read the first line");
    drop(stdout);

    let finished = child.wait_with_output().expect("wait for the CLI");
    let stderr = String::from_utf8_lossy(&finished.stderr);
    assert!(
        !stderr.contains("panicked"),
        "a closed pipe still panics:\n{stderr}"
    );
    assert!(
        finished.status.success(),
        "a closed pipe is a failure: {:?}\n{stderr}",
        finished.status,
    );
}

#[test]
fn a_real_failure_still_fails() {
    // The other end of the gate. The hush must not swallow anything else: a
    // refusal still has to reach stderr and still has to exit non-zero, or the
    // fix above would have made every error silent.
    let out = Command::new(VCW)
        .args(["eq", "show", "nosuchcurve"])
        .output()
        .expect("run the CLI");
    assert!(!out.status.success(), "an unknown curve succeeded");
    assert!(
        String::from_utf8_lossy(&out.stderr).contains("nosuchcurve"),
        "the refusal did not reach stderr",
    );
}
